    x0, y0, w, h = b
    # 策略决策（带外）
    rect(s, (x0, y0 + 4, w, 78), "grey_l", kind="rounded", radius=8)
    text(s, (x0 + 10, y0 + 7, 420, 20), "**策略决策**：在 Agent 进程之外判定每一次调用", style="detail", color="accent",
         check=False)
