    arrow(s, (cx + cw + 1, my + 31), (rx - 1, my + 31), color="dark", width=1.25)
    arrow(s, (cx + cw + 1, my + 149), (rx - 1, my + 149), color="dark", width=1.25)

    # 带外判定（虚线）：策略决策 → 三道关口
    arrow(s, (x0 + 14, y0 + 83), (x0 + 14, my + 43), color="red", dash=True)
